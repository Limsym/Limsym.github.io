let currentLanguage = "zh-CN";

function textFor(key) {
  return translations[currentLanguage][key] || translations["zh-CN"][key] || key;
}

function applyLanguage(language) {
  currentLanguage = translations[language] ? language : "zh-CN";
  localStorage.setItem("language", currentLanguage);
  document.documentElement.lang = currentLanguage;
  document.title = textFor("meta_title");
  document.querySelector('meta[name="description"]').content = textFor("meta_description");
  document.querySelector('meta[name="keywords"]').content = textFor("meta_keywords");

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = textFor(element.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-value]").forEach((element) => {
    element.value = textFor(element.dataset.i18nValue);
  });

  const languageToggle = document.getElementById("language-toggle");
  document.getElementById("language-toggle-text").textContent = currentLanguage === "zh-CN" ? "EN" : "中";
  languageToggle.setAttribute("aria-label", textFor("language_switch"));
  updateThemeLabel();
}

function updateThemeLabel() {
  const button = document.getElementById("theme-toggle");
  if (!button) return;
  const isDark = document.documentElement.dataset.theme === "dark";
  button.setAttribute("aria-label", textFor(isDark ? "theme_light" : "theme_dark"));
}

function initializeTheme() {
  const saved = localStorage.getItem("theme");
  const prefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
  const theme = saved || (prefersDark ? "dark" : "light");
  document.documentElement.dataset.theme = theme;
  document.querySelector('meta[name="theme-color"]').content = theme === "dark" ? "#111815" : "#f3f0e7";
}

function initializeReveal() {
  const items = document.querySelectorAll(".reveal");
  if (!("IntersectionObserver" in window)) {
    items.forEach((item) => item.classList.add("is-visible"));
    return;
  }
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.08 });
  items.forEach((item) => observer.observe(item));
}

function initializeNavigation() {
  const menuButton = document.getElementById("menu-toggle");
  const mobileNav = document.getElementById("mobile-nav");
  menuButton.addEventListener("click", () => {
    const opening = mobileNav.hidden;
    mobileNav.hidden = !opening;
    menuButton.setAttribute("aria-expanded", String(opening));
    menuButton.querySelector(".sr-only").textContent = textFor(opening ? "close_menu" : "open_menu");
  });
  mobileNav.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
    mobileNav.hidden = true;
    menuButton.setAttribute("aria-expanded", "false");
  }));

  const links = document.querySelectorAll('.desktop-nav a[href^="#"], .contents a[href^="#"]');
  const sections = [...document.querySelectorAll("main section[id]")];
  const updateActive = () => {
    const marker = window.scrollY + window.innerHeight * 0.28;
    let active = sections[0]?.id;
    sections.forEach((section) => { if (section.offsetTop <= marker) active = section.id; });
    links.forEach((link) => link.classList.toggle("active", link.getAttribute("href") === `#${active}`));
  };
  window.addEventListener("scroll", updateActive, { passive: true });
  updateActive();
}

function initializeProgress() {
  const bar = document.getElementById("progress-bar");
  const update = () => {
    const available = document.documentElement.scrollHeight - window.innerHeight;
    bar.style.width = `${available > 0 ? (window.scrollY / available) * 100 : 0}%`;
  };
  window.addEventListener("scroll", update, { passive: true });
  update();
}

function initializeContactForm() {
  const form = document.getElementById("contact-form");
  const status = document.getElementById("form-status");
  const button = form.querySelector('button[type="submit"]');
  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    if (!form.reportValidity()) return;
    button.disabled = true;
    status.textContent = textFor("form_submitting");
    try {
      const response = await fetch(form.action, { method: "POST", body: new FormData(form), headers: { Accept: "application/json" } });
      if (!response.ok) throw new Error("Form submission failed");
      form.reset();
      status.textContent = textFor("form_success");
    } catch (error) {
      status.textContent = textFor("form_error");
    } finally {
      button.disabled = false;
    }
  });
}

document.addEventListener("DOMContentLoaded", () => {
  initializeTheme();
  const savedLanguage = localStorage.getItem("language");
  const browserLanguage = navigator.language && navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
  applyLanguage(savedLanguage || browserLanguage);

  document.getElementById("language-toggle").addEventListener("click", () => applyLanguage(currentLanguage === "zh-CN" ? "en" : "zh-CN"));
  document.getElementById("theme-toggle").addEventListener("click", () => {
    const next = document.documentElement.dataset.theme === "dark" ? "light" : "dark";
    document.documentElement.dataset.theme = next;
    document.querySelector('meta[name="theme-color"]').content = next === "dark" ? "#111815" : "#f3f0e7";
    localStorage.setItem("theme", next);
    updateThemeLabel();
  });
  document.getElementById("print-resume").addEventListener("click", () => window.print());

  initializeNavigation();
  initializeProgress();
  initializeReveal();
  initializeContactForm();
});
